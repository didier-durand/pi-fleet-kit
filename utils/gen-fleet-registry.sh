#!/usr/bin/env bash
# Generate docs/agent-registry.md from compose.yml — the fleet's "who does
# what" table. compose.yml is the single source of truth; this file is
# ALWAYS generated, never hand-edited.
#
# Usage:
#   utils/gen-fleet-registry.sh                  # ./compose.yml -> docs/agent-registry.md
#   utils/gen-fleet-registry.sh <compose-file>   # read another compose file
#   utils/gen-fleet-registry.sh <compose> -      # write to stdout instead
#
# The pre-commit hook regenerates from the STAGED compose.yml and refuses
# the commit if the staged registry would drift from it.

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE="${1:-$REPO_DIR/compose.yml}"
OUT="${2:-$REPO_DIR/docs/agent-registry.md}"

[[ -f "$COMPOSE" ]] || { echo "error: compose file not found: $COMPOSE" >&2; exit 1; }

table="$(awk '
  # Only the services section matters; the top-level volumes: block ends it.
  /^volumes:/ { sec = "volumes" }
  sec != "volumes" && /^  [a-z0-9-]+:$/ {
    if (svc != "") flush()
    svc = $1; sub(/:$/, "", svc)
    home = ""; ws = ""; exch = ""; skills = ""; exts = ""; trig = ""
  }
  svc != "" && /- [a-z0-9-]+:\/home\/pi\/\.pi\/agent$/ {
    line = $0; sub(/^.*- /, "", line); sub(/:.*/, "", line); home = line
  }
  svc != "" && /pi-agents\/[a-z0-9-]+:\/workspace/ {
    line = $0; sub(/^.*pi-agents\//, "", line); sub(/:\/workspace.*$/, "", line); ws = line
  }
  svc != "" && /pi-exchange\/[a-z0-9-]+:\/exchange/ {
    line = $0; sub(/^.*pi-exchange\//, "", line); sub(/:\/exchange.*$/, "", line); exch = line
  }
  svc != "" && /--skill", "\/repo-skills\// {
    line = $0
    while (match(line, /--skill", "\/repo-skills\/[a-z0-9-]+"/)) {
      s = substr(line, RSTART, RLENGTH)
      sub(/^.*repo-skills\//, "", s); sub(/"$/, "", s)
      skills = (skills == "" ? s : skills ", " s)
      line = substr(line, RSTART + RLENGTH)
    }
  }
  svc != "" && /--extension", "\/repo-extensions\// {
    line = $0
    while (match(line, /--extension", "\/repo-extensions\/[a-z0-9-]+\//)) {
      s = substr(line, RSTART, RLENGTH)
      sub(/^.*repo-extensions\//, "", s); sub(/\/$/, "", s)
      exts = (exts == "" ? s : exts ", " s)
      line = substr(line, RSTART + RLENGTH)
    }
  }
  svc != "" && /PI_TRIGGER_DIR/ { trig = "set" }
  END { if (svc != "") flush() }
  function flush() {
    pt = "dormant"
    if (exch != "")      pt = "active — ~/pi-exchange/" exch
    else if (trig != "") pt = "active — /exchange (external mount)"
    order[++n] = svc
    rows[svc] = "| " svc " | " home " | " (skills == "" ? "—" : skills) " | " \
                (exts == "" ? "—" : exts) " | " pt " | ~/pi-agents/" ws " |"
  }
  END {
    print "| Agent | Pi home volume | Skills | Extensions | Prompt trigger | Workspace (host) |"
    print "|---|---|---|---|---|---|"
    for (i = 1; i <= n; i++) print rows[order[i]]
  }
' "$COMPOSE")"

if [[ "$OUT" == "-" ]]; then
  cat <<HEADER
# Fleet registry

<!-- Generated by utils/gen-fleet-registry.sh from compose.yml — DO NOT EDIT BY HAND.
     Regenerate after any fleet config change; the pre-commit hook verifies freshness. -->

${table}
HEADER
else
  cat > "$OUT" <<HEADER
# Fleet registry

<!-- Generated by utils/gen-fleet-registry.sh from compose.yml — DO NOT EDIT BY HAND.
     Regenerate after any fleet config change; the pre-commit hook verifies freshness. -->

${table}
HEADER
  echo "registry written: $OUT ($(grep -c '^| pi-' "$OUT") agents)"
fi
