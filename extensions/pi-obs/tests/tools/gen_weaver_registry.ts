/**
 * pi-obs — Weaver registry generator (DEV_PLAN Step 9, standard-tools level).
 *
 * Generates the `pi.*` semantic-convention registry in Weaver's
 * `definition/2` format FROM `semconv.ts` — the add-only registry IS the
 * contract, so the conformance registry is generated from it, never
 * hand-maintained. The GenAI attributes are NOT defined here: the span
 * group references them (`ref: gen_ai.…`) and they resolve from the
 * PINNED upstream dependency declared in `manifest.yaml`
 * (semantic-conventions v1.40.0, fetched and cached by weaver itself).
 *
 * Usage:
 *   node tests/tools/gen_weaver_registry.ts > tests/tools/weaver/pi_registry.yaml
 *
 * The generated file is CHECKED IN (like the docs transcripts): re-run
 * whenever semconv.ts changes. The generator also carries the
 * entity→attribute mapping from SPECS R3's inventory (which attributes
 * belong on which span/event/metric) and the number→int/double OTel
 * type mapping — both documented in place.
 */

import { EVENT_NAMES, GENAI_ATTRIBUTES, METRICS, PI_ATTRIBUTES, RESOURCE_ATTRIBUTES, SPAN_NAMES } from "../../src/semconv.ts";

/** OTel attribute types: semconv's "number" splits into int/double (OTLP wire encodes them differently). */
const OTEL_TYPE: Record<string, "string" | "int" | "double" | "boolean"> = {
	// number → int (integer-valued counters/indices/durations in ms)
	"pi.turn.index": "int",
	"pi.tokens.before": "int",
	"pi.duration.ms": "int",
	"pi.messages.in": "int",
	"pi.messages.out": "int",
	"pi.content.length": "int",
	"pi.dropped.count": "int",
	// number → double (monetary)
	"pi.cost.total": "double",
};

/** The entity→attribute mapping (SPECS R3's usage inventory). */
const SPAN_ATTRS: Record<string, string[]> = {
	"pi.session": ["pi.session.id", "pi.session.file", "pi.session.reason", "pi.cwd"],
	"pi.run": [],
	"pi.turn": ["pi.turn.index"],
	"pi.model": [
		"gen_ai.operation.name",
		"gen_ai.system",
		"gen_ai.request.model",
		"gen_ai.response.model",
		"gen_ai.response.id",
		"gen_ai.usage.input_tokens",
		"gen_ai.usage.output_tokens",
		"pi.stop_reason",
		"pi.cost.total",
	],
	"pi.tool": ["pi.tool.name", "pi.tool.path", "pi.tool.command", "pi.tool.result", "pi.tool.is_error"],
};

const EVENT_ATTRS: Record<string, string[]> = {
	"pi.session.renamed": [],
	"pi.session.switch": ["pi.reason", "pi.target"],
	"pi.session.fork": ["pi.reason", "pi.target"],
	"pi.session.compact": ["pi.reason", "pi.outcome", "pi.tokens.before"],
	"pi.session.tree": ["pi.target", "pi.summary"],
	"pi.resources": ["pi.reason", "pi.cwd"],
	"pi.user.input": ["pi.source", "pi.streaming", "pi.content.length", "pi.content.hash", "pi.content.text"],
	"pi.user.bash": ["pi.tool.command"],
	"pi.ui.prompt": ["pi.kind", "pi.duration.ms"],
	"pi.model.headers": ["pi.header.names"],
	"pi.model.response_status": ["pi.status"],
	"pi.session.model_change": ["pi.provider", "pi.model.id"],
	"pi.session.thinking_level_change": ["pi.level"],
	"pi.model.cache_warming": ["pi.decision"],
	"pi.context": ["pi.messages.in", "pi.messages.out"],
	"pi.tool.outcome": ["pi.outcome", "pi.tool.path", "pi.tool.command"],
	"pi.run.aborted": ["pi.aborted"],
};

/** Resource attributes our OTLP resource carries (service.* resolve from the pinned dependency). */
const RESOURCE_ATTRS = ["service.name", "service.version", "pi.version", "pi.replayed", "pi.replay.source", "pi.cwd"];

const yq = (text: string): string => `"${text.replaceAll('"', "'").replaceAll("\n", " ")}"`;

const lines: string[] = [];
lines.push("# GENERATED by tests/tools/gen_weaver_registry.ts from semconv.ts — DO NOT EDIT.");
lines.push("# Regenerate: node tests/tools/gen_weaver_registry.ts > tests/tools/weaver/pi_registry.yaml");
lines.push("# The gen_ai.* references resolve from the pinned dependency in manifest.yaml");
lines.push("# (semantic-conventions v1.40.0). pi.* is the pi-obs custom namespace (R4).");
lines.push("file_format: definition/2");
lines.push("");

// --- attributes (pi.* + pi.*-identifying resource attrs; gen_ai.* resolve from the dependency) ---
const ownAttributes = [...PI_ATTRIBUTES, ...RESOURCE_ATTRIBUTES.filter((a) => a.name.startsWith("pi."))];
lines.push("attributes:");
for (const attr of ownAttributes) {
	const type = attr.type === "number" ? (OTEL_TYPE[attr.name] ?? "double") : attr.type;
	lines.push(`  - key: ${attr.name}`);
	lines.push(`    type: ${type}`);
	lines.push(`    stability: development`);
	lines.push(`    brief: ${yq(attr.meaning)}`);
}
lines.push("");

// --- attribute groups (matched by the resource / span-event matchers in .weaver.toml) ---
const eventAttrNames = [...new Set(Object.values(EVENT_ATTRS).flat())];
lines.push("attribute_groups:");
lines.push("  - id: pi.obs.resource");
lines.push("    visibility: public");
lines.push("    stability: development");
lines.push('    brief: "The OTLP resource every pi-obs record carries."');
lines.push("    attributes:");
for (const name of RESOURCE_ATTRS) {
	lines.push(`      - ref: ${name}`);
	lines.push(`        requirement_level: recommended`);
}
lines.push("  - id: pi.obs.event_attributes");
lines.push("    visibility: public");
lines.push("    stability: development");
lines.push('    brief: "Attributes carried on the pi-obs span events (R3 usage inventory)."');
lines.push("    attributes:");
for (const name of eventAttrNames) {
	lines.push(`      - ref: ${name}`);
	lines.push(`        requirement_level: recommended`);
}
lines.push("");

// --- spans ---
lines.push("spans:");
for (const span of SPAN_NAMES) {
	lines.push(`  - type: ${span.name}`);
	lines.push(`    name:`);
	lines.push(`      note: ${yq(`The constant \`${span.name}\`${span.name === "pi.tool" ? " plus the tool name suffix" : ""}.`)}`);
	lines.push(`    kind: internal`);
	lines.push(`    stability: development`);
	lines.push(`    brief: ${yq(span.meaning)}`);
	const attrs = SPAN_ATTRS[span.name] ?? [];
	if (attrs.length > 0) {
		lines.push(`    attributes:`);
		for (const name of attrs) {
			lines.push(`      - ref: ${name}`);
			lines.push(`        requirement_level: recommended`);
		}
	}
}
lines.push("");

// --- events ---
lines.push("events:");
for (const event of EVENT_NAMES) {
	lines.push(`  - name: ${event.name}`);
	lines.push(`    stability: development`);
	lines.push(`    brief: ${yq(event.meaning)}`);
	const attrs = EVENT_ATTRS[event.name] ?? [];
	if (attrs.length > 0) {
		lines.push(`    attributes:`);
		for (const name of attrs) {
			lines.push(`      - ref: ${name}`);
			lines.push(`        requirement_level: recommended`);
		}
	}
}
lines.push("");

// --- metrics ---
lines.push("metrics:");
for (const metric of METRICS) {
	lines.push(`  - name: ${metric.name}`);
	lines.push(`    brief: ${yq(metric.meaning)}`);
	lines.push(`    stability: development`);
	lines.push(`    instrument: ${metric.type === "counter" ? "counter" : "histogram"}`);
	lines.push(`    unit: ${yq(metric.unit)}`);
	if (metric.attributes.length > 0) {
		lines.push(`    attributes:`);
		for (const name of metric.attributes) {
			lines.push(`      - ref: ${name}`);
			lines.push(`        requirement_level: recommended`);
		}
	}
}
lines.push("");

process.stdout.write(lines.join("\n"));
void GENAI_ATTRIBUTES; // gen_ai.* resolve from the pinned dependency — referenced, not defined
