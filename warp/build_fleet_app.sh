#!/usr/bin/env bash
# Build "Pi Agent Fleet.app" — a stay-open macOS applet for the Dock.
#
# Why not a plain one-shot launcher (e.g. an Automator app)? It exits
# immediately after the click, so:
#   - the Dock never shows the standard black "running" dot;
#   - a click while it "runs" cannot be handled (macOS only re-activates).
#
# The applet built here:
#   - runs agents_start.sh on launch AND on every Dock click while running
#     (the reopen event) — every click still converges the fleet: missing
#     agents are added, running ones skipped, orphans healed;
#   - stays running while any agent container is up  -> black dot visible;
#   - auto-quits ~60s after the last agent stops      -> dot disappears.
#
# Usage:
#   ./build_fleet_app.sh               # build into ~/Applications
#   ./build_fleet_app.sh /Applications  # build into /Applications
#
# Requirements: macOS (osacompile, sips, iconutil). After building, remove
# any old launcher app from the Dock and drag "Pi Agent Fleet.app" in.
# The icon is generated from AI-agent-fleet-Icon.png next to this script.

set -euo pipefail

WARP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# Prefer the rounded RGBA version (proper macOS icon: transparent corners);
# fall back to the raw PNG.
ICON_SRC="$WARP_DIR/AI-agent-fleet-Icon-rounded.png"
[[ -f "$ICON_SRC" ]] || ICON_SRC="$WARP_DIR/AI-agent-fleet-Icon.png"
APP_NAME="Pi Agent Fleet.app"
DEST="${1:-$HOME/Applications}"

[[ "$(uname -s)" == "Darwin" ]] || { echo "error: macOS only (needs osacompile/sips/iconutil)" >&2; exit 1; }
[[ -f "$ICON_SRC" ]] || { echo "error: icon not found: $ICON_SRC" >&2; exit 1; }
[[ -f "$WARP_DIR/agents_start.sh" ]] || { echo "error: agents_start.sh not found next to this script" >&2; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# --- 1. AppleScript applet ------------------------------------------------------

cat > "$WORK/fleet.applescript" <<'EOF'
-- Pi Agent Fleet: stay-open launcher (generated by build_fleet_app.sh)
-- Launch and every Dock click run agents_start.sh (idempotent: adds
-- missing agents, skips running ones, heals orphans). The app stays open
-- while any agent container is running (Dock black dot) and quits shortly
-- after the whole fleet stops.

property GraceSeconds : 60
property LastSeenUp : missing value

on run
	startFleet()
end run

on reopen
	startFleet()
end reopen

on startFleet()
	try
		do shell script "nohup $HOME/pi-configs/warp/agents_start.sh > /tmp/pi-agent-fleet.log 2>&1 & exit 0"
	end try
	set LastSeenUp to (current date)
end startFleet

on idle
	if fleetUp() then
		set LastSeenUp to (current date)
	else if LastSeenUp is not missing value and ((current date) - LastSeenUp) > GraceSeconds then
		tell me to quit
	end if
	return 15
end idle

on fleetUp()
	repeat with agentName in {"pi-configs", "pi-coding", "pi-research", "pi-personal"}
		try
			do shell script "/bin/bash $HOME/pi-configs/warp/agent_run.sh --check " & agentName
			return true
		end try
	end repeat
	return false
end fleetUp
EOF

osacompile -o "$WORK/$APP_NAME" "$WORK/fleet.applescript"
echo "  compiled applet: $APP_NAME"

# --- 2. Icon (.icns) ------------------------------------------------------------

ICONSET="$WORK/AppIcon.iconset"
mkdir -p "$ICONSET"
if ls "$WARP_DIR/iconset"/icon_*.png >/dev/null 2>&1; then
  # Precomputed, high-quality iconset committed to the repo (exact box-filter
  # resampling with premultiplied alpha — much better than sips downscaling).
  cp "$WARP_DIR/iconset"/icon_*.png "$ICONSET/"
  echo "  icon: using precomputed iconset/ (10 sizes, 16..1024)"
else
  # Fallback: generate from the artwork PNG with sips.
  for s in 16 32 128 256 512; do
    sips -z "$s" "$s" "$ICON_SRC" --out "$ICONSET/icon_${s}x${s}.png" >/dev/null
    s2=$(( s * 2 ))
    sips -z "$s2" "$s2" "$ICON_SRC" --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null
  done
  echo "  icon: generated from $(basename "$ICON_SRC") (sips)"
fi
iconutil -c icns "$ICONSET" -o "$WORK/$APP_NAME/Contents/Resources/AppIcon.icns"

# --- 3. Bundle metadata -----------------------------------------------------------

PLIST="$WORK/$APP_NAME/Contents/Info.plist"
plist_set() {  # plist_set <key> <value>  (Set if present, Add as string otherwise)
  local key="$1" val="$2"
  /usr/libexec/PlistBuddy -c "Set :$key $val" "$PLIST" 2>/dev/null \
    || /usr/libexec/PlistBuddy -c "Add :$key string $val" "$PLIST"
}
plist_set CFBundleIconFile AppIcon.icns
plist_set CFBundleIdentifier com.pi-configs.agent-fleet
plist_set CFBundleName "Pi Agent Fleet"
# Modern icon keys, if present, take precedence over CFBundleIconFile —
# remove them so our icon reference is the one Finder uses.
/usr/libexec/PlistBuddy -c "Delete :CFBundleIcons" "$PLIST" >/dev/null 2>&1 || true
/usr/libexec/PlistBuddy -c "Delete :CFBundleIconName" "$PLIST" >/dev/null 2>&1 || true
touch "$WORK/$APP_NAME"
# sanity: the icon file reference must be exactly this (no stray "string")
grep -q "<string>AppIcon.icns</string>" "$PLIST" \
  || { echo "error: CFBundleIconFile not set correctly" >&2; exit 1; }

# --- 4. Install -------------------------------------------------------------------

mkdir -p "$DEST"
rm -rf "$DEST/$APP_NAME"
cp -R "$WORK/$APP_NAME" "$DEST/$APP_NAME"
touch "$DEST/$APP_NAME"

# Force LaunchServices to re-read the bundle (icon cache busting).
LSREG="/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister"
[[ -x "$LSREG" ]] && "$LSREG" -f "$DEST/$APP_NAME" >/dev/null 2>&1 || true

echo
echo "Built: $DEST/$APP_NAME"
echo "Next:"
echo "  1. Remove any previous launcher app from the Dock."
echo "  2. Drag '$APP_NAME' into the Dock."
echo "  3. Click it: fleet starts; dot shows while agents run, disappears ~60s after the last one stops."
